/**
 * `.opencode/package.json` for the tool runtime dependency. Minimal
 * and pinned: OpenCode runs `bun install` at startup per its plugin
 * contract; without it the tools directory stays inert (fail-closed,
 * never silently ungoverned).
 */
export function buildPlanningToolsPackage(): string {
  return JSON.stringify({ dependencies: { [OPENCODE_PLUGIN_DEP]: OPENCODE_PLUGIN_PIN } }, null, 2) + "\n";
}

/**
 * Drift state of the managed tool runtime against these bytes.
 * `marker` entries tolerate user-owned content; the tool file itself
 * is byte-exact.
 */
export type PlanningToolsState =
  | { readonly state: "ok" }
  | { readonly state: "missing"; readonly reason: string }
  | { readonly state: "drifted"; readonly reason: string };

export function checkPlanningToolsFile(existing: string | null): PlanningToolsState {
  if (existing === null) {
    return { state: "missing", reason: "project planning tools are missing: run chrono init --runtime opencode to install the governed native tools" };
  }
  if (existing !== buildPlanningToolsFile()) {
    return { state: "drifted", reason: "project planning tools differ from the managed bytes: re-run chrono init --runtime opencode to reconcile (hand edits are drift, not input)" };
  }
  return { state: "ok" };
}

