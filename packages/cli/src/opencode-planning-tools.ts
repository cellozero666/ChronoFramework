import { tool } from "@opencode-ai/plugin";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, realpathSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createHash } from "node:crypto";

const TOKEN_PREFIX = "chrono-gaspar-host-";
const TOKEN_SUFFIX = ".token";

function sha16(text) {
  return createHash("sha256").update(text, "utf8").digest("hex").slice(0, 16);
}

function fail(message) {
  throw new Error("[chrono] " + message);
}

function projectRoot(directory) {
  let canonical;
  try {
    canonical = realpathSync(directory);
  } catch {
    fail("cannot resolve project directory: " + directory);
  }
  try {
    if (!existsSync(join(canonical, ".chrono", "chrono.db"))) {
      fail("no CHRONO project at " + canonical + ": run chrono init first");
    }
  } catch {
    fail("cannot inspect project directory: " + canonical);
  }
  return canonical;
}

function hostToken(root, sessionID) {
  // Host-only Gaspar entry credential for this exact OpenCode
  // session. Written by the entry flow (CHRONO_TOKEN_OUT); read here
  // for Core calls. Never returned, never logged.
  const path = join(tmpdir(), TOKEN_PREFIX + sha16(root + "|" + sessionID) + TOKEN_SUFFIX);
  let raw = "";
  try {
    raw = readFileSync(path, "utf8").trim();
  } catch {
    fail("no Gaspar entry session for this OpenCode session: reopen OpenCode so entry redeems (never export tokens yourself)");
  }
  if (raw.indexOf("/") <= 0) {
    fail("entry session credential is malformed: reopen OpenCode so entry redeems");
  }
  return raw;
}

function chronoBin() {
  const fromEnv = process.env["CHRONO_BIN"];
  return fromEnv === undefined || fromEnv === "" ? "chrono" : fromEnv;
}

function runChrono(argv, stdinText) {
  const ran = spawnSync(chronoBin(), argv, {
    input: stdinText,
    encoding: "utf8",
    timeout: 120000,
    stdio: ["pipe", "pipe", "pipe"],
  });
  const stdout = typeof ran.stdout === "string" ? ran.stdout : "";
  try {
    return { exit: ran.status ?? 1, json: JSON.parse(stdout) };
  } catch {
    return { exit: 1, json: { ok: false, error: { code: "GATE_UNREACHABLE", message: "chrono returned non-JSON output" } } };
  }
}

function deny(result, fallback) {
  const code = result?.error?.code;
  const reason = result?.error?.message;
  fail(typeof code === "string" && typeof reason === "string" ? code + ": " + reason : fallback);
}

const commonArgs = (root, token) => ["--as", "gaspar", "--session-token", token, "--path", root, "--json"];

// Lifecycle tools run as the calling session's own agent (Gaspar,
// worker, or reviewer): the host-held credential selects the Core
// session and the Core enforces role capabilities and scope per
// call. Unknown agent names fail closed at the Core.
const callerAgent = (context) => (context !== null && typeof context === "object" && typeof context.agent === "string" && context.agent.length > 0 ? context.agent : "gaspar");
const agentArgs = (root, token, agent) => ["--as", agent, "--session-token", token, "--path", root, "--json"];

export const artifact_status = tool({
  description: "CHRONO planning status: safe projection of drafts (proposed, awaiting PO signature, approved, rejected, stale). No secrets.",
  args: {},
  async execute(_args, context) {
    const root = projectRoot(context.directory);
    const token = hostToken(root, context.sessionID);
    const res = runChrono(["artifact", "status", ...commonArgs(root, token)]);
    if (res.exit !== 0 || res.json?.ok !== true) {
      deny(res.json, "planning status denied");
    }
    return JSON.stringify(res.json);
  },
});

